#!/usr/bin/env node
'use strict';
// Dependency-free packaging: concatenates src/*.js into the single main.js that
// Obsidian loads (Obsidian cannot require() sibling files). Uses only Node built-ins.
//   node scripts/build.js          write main.js
//   node scripts/build.js --check  fail if main.js is out of date
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ORDER = ['constants', 'task-identity', 'task-discovery', 'task-storage', 'task-index', 'dnd',
  'overview-view', 'queue-view', 'dashboard-view', 'settings', 'main'];

let out = `/* GENERATED by scripts/build.js from src/*.js. Edit the files in src/, then rebuild. */\n'use strict';\n`;
out += `const __defs = {};\nconst __cache = {};\n`;
out += `function __load(name) {\n  if (__cache[name]) return __cache[name].exports;\n  const m = (__cache[name] = { exports: {} });\n`;
out += `  __defs[name](m, m.exports, (n) => (n.startsWith('./') ? __load(n) : require(n)));\n  return m.exports;\n}\n`;
for (const name of ORDER) {
  const src = fs.readFileSync(path.join(root, 'src', name + '.js'), 'utf8').replace(/^'use strict';\n/, '');
  out += `\n// ---- src/${name}.js ----\n__defs['./${name}'] = function (module, exports, require) {\n${src}};\n`;
}
out += `\nmodule.exports = __load('./main');\n`;

const target = path.join(root, 'main.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== out) { console.error('main.js is out of date. Run: node scripts/build.js'); process.exit(1); }
  console.log('main.js is up to date.');
} else {
  fs.writeFileSync(target, out);
  console.log(`Wrote main.js (${out.length} bytes)`);
}
